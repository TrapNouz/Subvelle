"""Draws the Subvelle mark (rounded hexagon ring with an orbiting planet) and writes the app icons.

One geometry, every output: the iPhone app icon (1024 px PNG), the in-app mark for both apps
(vector), and Android's adaptive launcher icon with its themed (monochrome) layer.
Usage: python3 Tools/GenerateAppIcon.py   (needs: pip install cairosvg)
"""
import json, math, os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RING_LIGHT, RING_DARK = "#BAA8FA", "#6B47D1"
PLANET_LIGHT, PLANET_DARK = "#7E62F2", "#4C33D6"
BACKGROUND = "#0B0B0E"

def geometry(cx, cy, R):
    """Hexagon ring path (open at the upper-right corner) and the planet in that gap."""
    v = [(cx + R * math.cos(math.radians(-90 + 60 * k)), cy + R * math.sin(math.radians(-90 + 60 * k))) for k in range(6)]
    lerp = lambda a, b, t: (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    start = lerp(v[0], v[1], 0.40)          # on the top-right edge
    end = lerp(v[1], v[2], 0.20)            # on the right edge, just below the planet
    points = [start, v[0], v[5], v[4], v[3], v[2], end]
    path = "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points)
    planet = (v[1][0] - 0.17 * R, v[1][1] - 0.13 * R)   # tucked into the open corner
    return path, planet, 0.28 * R, 0.25 * R, 0.07 * R   # path, planet centre, ring width, planet radius, gap

def svg_mark(size, R, background=None):
    c = size / 2
    path, (px, py), width, pr, gap = geometry(c, c + R * 0.02, R)
    bg = ""
    if background:
        bg = (f'<defs><radialGradient id="bg" cx="50%" cy="42%" r="70%"><stop offset="0" stop-color="#1C1633"/>'
              f'<stop offset="1" stop-color="{background}"/></radialGradient></defs>'
              f'<rect width="{size}" height="{size}" fill="url(#bg)"/>')
    gap_colour = background or "#0B0B0E"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">{bg}'
            f'<defs><linearGradient id="ring" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{RING_LIGHT}"/><stop offset="1" stop-color="{RING_DARK}"/></linearGradient>'
            f'<linearGradient id="planet" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{PLANET_LIGHT}"/><stop offset="1" stop-color="{PLANET_DARK}"/></linearGradient></defs>'
            f'<path d="{path}" fill="none" stroke="url(#ring)" stroke-width="{width:.2f}" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<circle cx="{px:.2f}" cy="{py:.2f}" r="{pr + gap:.2f}" fill="{gap_colour}"/>'
            f'<circle cx="{px:.2f}" cy="{py:.2f}" r="{pr:.2f}" fill="url(#planet)"/></svg>')

def vector_drawable(viewport, R, monochrome=False, gap_colour="#FF0B0B0E"):
    """Android vector: gradient ring and planet (or plain white for the themed icon)."""
    c = viewport / 2
    path, (px, py), width, pr, gap = geometry(c, c + R * 0.02, R)
    circle = lambda r: f"M{px - r:.3f},{py:.3f} a{r:.3f},{r:.3f} 0 1,0 {2 * r:.3f},0 a{r:.3f},{r:.3f} 0 1,0 {-2 * r:.3f},0 Z"
    lo, hi = c - R, c + R
    def gradient(attr, a, b):
        return (f'        <aapt:attr name="{attr}">\n            <gradient android:type="linear" android:startX="{lo:.2f}" android:startY="{lo:.2f}" '
                f'android:endX="{hi:.2f}" android:endY="{hi:.2f}" android:startColor="#FF{a[1:]}" android:endColor="#FF{b[1:]}" />\n        </aapt:attr>\n')
    if monochrome:
        ring = f'    <path android:pathData="{path}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{width:.3f}" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
        planet = f'    <path android:pathData="{circle(pr)}" android:fillColor="#FFFFFFFF" />\n'
        separator = ""
    else:
        ring = (f'    <path android:pathData="{path}" android:strokeWidth="{width:.3f}" android:strokeLineCap="round" android:strokeLineJoin="round">\n'
                + gradient("android:strokeColor", RING_LIGHT, RING_DARK) + '    </path>\n')
        separator = f'    <path android:pathData="{circle(pr + gap)}" android:fillColor="{gap_colour}" />\n'
        planet = f'    <path android:pathData="{circle(pr)}">\n' + gradient("android:fillColor", PLANET_LIGHT, PLANET_DARK) + '    </path>\n'
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Subvelle mark. Generated by Tools/GenerateAppIcon.py; do not edit by hand. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{viewport}dp" android:height="{viewport}dp"\n    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
            + ring + separator + planet + '</vector>\n')

if __name__ == "__main__":
    import cairosvg
    ios = os.path.join(REPO, "Subspace/Resources/Assets.xcassets")
    # iPhone app icon: full-bleed dark background, mark about 60% of the height.
    cairosvg.svg2png(bytestring=svg_mark(1024, 300, BACKGROUND).encode(), write_to=os.path.join(ios, "AppIcon.appiconset/AppIcon.png"), output_width=1024, output_height=1024)
    # In-app mark (transparent, vector).
    mark = os.path.join(ios, "SubvelleMark.imageset"); os.makedirs(mark, exist_ok=True)
    open(os.path.join(mark, "SubvelleMark.svg"), "w").write(svg_mark(100, 42))
    json.dump({"images": [{"filename": "SubvelleMark.svg", "idiom": "universal"}], "info": {"author": "xcode", "version": 1},
               "properties": {"preserves-vector-representation": True, "template-rendering-intent": "original"}},
              open(os.path.join(mark, "Contents.json"), "w"), indent=2)
    res = os.path.join(REPO, "android/app/src/main/res")
    # Adaptive icon foreground: 108 dp canvas, the mark kept inside the 66 dp safe zone.
    open(os.path.join(res, "drawable/ic_launcher_foreground.xml"), "w").write(vector_drawable(108, 27.5, gap_colour="#FF0B0B0E"))
    open(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), "w").write(vector_drawable(108, 27.5, monochrome=True))
    open(os.path.join(res, "drawable/subvelle_mark.xml"), "w").write(vector_drawable(100, 42, gap_colour="#FF0B0B0E"))
    print("icons written")
